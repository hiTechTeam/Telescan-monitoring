#!/usr/bin/env bash
set -Eeuo pipefail

test_mode="${TELESCAN_DOCKER_GC_TEST_MODE:-0}"
if [[ "$test_mode" == 1 ]]; then
  config_file="${TELESCAN_DOCKER_GC_CONFIG_FILE:?test config is required}"
  lock_file="${TELESCAN_DOCKER_GC_LOCK_FILE:?test lock is required}"
  transaction_root="${TELESCAN_DOCKER_GC_TRANSACTION_ROOT:?test transaction root is required}"
  docker_bin="${TELESCAN_DOCKER_GC_DOCKER_BIN:?test Docker shim is required}"
  flock_bin="${TELESCAN_DOCKER_GC_FLOCK_BIN:?test flock shim is required}"
  case "$(realpath "$config_file")" in
    /tmp/telescan-docker-gc-test.*/*|/private/tmp/telescan-docker-gc-test.*/*) ;;
    *) echo "Unsafe test config path" >&2; exit 2 ;;
  esac
  case "$(realpath "$lock_file")" in
    /tmp/telescan-docker-gc-test.*/*|/private/tmp/telescan-docker-gc-test.*/*) ;;
    *) echo "Unsafe test lock path" >&2; exit 2 ;;
  esac
  case "$(realpath "$transaction_root")" in
    /tmp/telescan-docker-gc-test.*/*|/private/tmp/telescan-docker-gc-test.*/*) ;;
    *) echo "Unsafe test transaction path" >&2; exit 2 ;;
  esac
elif [[ "$test_mode" == 0 ]]; then
  [[ "$(id -un)" == ubuntu ]] || {
    echo "Docker build-cache maintenance must run as the production deploy user." >&2
    exit 1
  }
  config_file=/etc/default/telescan-monitoring-agent
  lock_file=/tmp/telescan-production-deploy.lock
  transaction_root=/home/ubuntu/telescan/.transactions
  docker_bin=/usr/bin/docker
  flock_bin=/usr/bin/flock
else
  echo "Invalid test mode." >&2
  exit 2
fi

[[ -f "$config_file" && ! -L "$config_file" ]] || {
  echo "Monitoring agent configuration is unavailable." >&2
  exit 1
}
# The file is generated by the root-only agent installer using shell escaping.
# shellcheck disable=SC1090
source "$config_file"

if [[ "${TELESCAN_HOST:-}" != moscow ]]; then
  echo "Docker build-cache maintenance is not required on this host."
  exit 0
fi

[[ -x "$docker_bin" ]] || {
  echo "Docker client is unavailable." >&2
  exit 1
}
[[ -x "$flock_bin" ]] || {
  echo "flock is unavailable." >&2
  exit 1
}

exec 9>"$lock_file"
if ! "$flock_bin" --nonblock 9; then
  echo "Production deployment is active; build-cache maintenance was skipped."
  exit 0
fi

if [[ -d "$transaction_root" ]] &&
   find "$transaction_root" -maxdepth 3 -type f -name active.json -print -quit |
     grep -q .; then
  echo "A durable recovery transaction is active; build-cache maintenance was skipped."
  exit 0
fi

"$docker_bin" builder prune --all --force --filter until=24h
